// layer-design-system.mjs — wrap the design-system component recipes in @layer components.
//
// WHY THIS EXISTS
//   Reliquary emits the recipes UNLAYERED, scoped as `.ds .ds-card` (specificity 0,2,0). An
//   unlayered rule beats ANY layered rule regardless of specificity, and Tailwind's utilities
//   live in `@layer utilities` — so every utility you put on a .ds-* element (`p-0`, `flex`,
//   `w-20`) is silently INERT, and the recipe's own `flex-direction: column` wins. Mixing a
//   utility onto a recipe class is the normal way to use this package, so that is a bug.
//
//   The CSS-native fix is `@import "./components.css" layer(components)`, but Next/Turbopack
//   DROPS the layer() on the import — verified in the compiled output: `@layer components;`
//   was emitted as an empty statement while the recipes landed unlayered at the end of the
//   file, after `@layer utilities`. So we wrap them at the source instead, which does not
//   depend on the bundler honouring @import layer().
//
//   @keyframes and @property are hoisted OUT of the layer: keyframes are not subject to the
//   cascade layer anyway, and @property is a top-level at-rule.
//
//   Re-run this after re-vendoring the design system:
//     node scripts/layer-design-system.mjs

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src", "design-system", "components");
const out = join(root, "src", "design-system", "components.layered.css");

// Pull top-level `@rule ... { ... }` blocks out. Brace-aware (a regex shatters on nesting),
// and — the bit that bites — COMMENT- and STRING-aware. These recipes carry prose like
//   /* @property numbers are animated from the element's own x-scroll ... */
// and a naive scan treats that `@property` as a real at-rule, tears the comment in half and
// leaves a stray apostrophe that PostCSS reports as "Unterminated string".
function extractTopLevel(css, names) {
  const hoisted = [];
  let rest = "";
  let i = 0;
  const n = css.length;

  while (i < n) {
    // comment — copy verbatim, never scan inside
    if (css[i] === "/" && css[i + 1] === "*") {
      const end = css.indexOf("*/", i + 2);
      const to = end === -1 ? n : end + 2;
      rest += css.slice(i, to);
      i = to;
      continue;
    }
    // string — copy verbatim (honouring backslash escapes)
    if (css[i] === '"' || css[i] === "'") {
      const q = css[i];
      let j = i + 1;
      while (j < n) {
        if (css[j] === "\\") { j += 2; continue; }
        if (css[j] === q) { j++; break; }
        j++;
      }
      rest += css.slice(i, j);
      i = j;
      continue;
    }
    if (css[i] === "@") {
      const name = (css.slice(i + 1).match(/^[a-z-]+/i) || [""])[0].toLowerCase();
      if (names.includes(name)) {
        const open = css.indexOf("{", i);
        if (open !== -1) {
          let depth = 0;
          let j = open;
          for (; j < n; j++) {
            if (css[j] === "{") depth++;
            else if (css[j] === "}") {
              depth--;
              if (depth === 0) { j++; break; }
            }
          }
          hoisted.push(css.slice(i, j));
          i = j;
          continue;
        }
      }
    }
    rest += css[i];
    i++;
  }
  return { hoisted, rest };
}

const files = readdirSync(dir).filter((f) => f.endsWith(".css")).sort();
const allHoisted = [];
const layered = [];

for (const f of files) {
  const css = readFileSync(join(dir, f), "utf8");
  const { hoisted, rest } = extractTopLevel(css, ["keyframes", "property"]);
  allHoisted.push(...hoisted);
  layered.push(`  /* ---- ${f} ---- */\n` + rest.trim().replace(/^/gm, "  "));
}

const banner = `/* GENERATED by scripts/layer-design-system.mjs — do not edit by hand.
 *
 * The recipes, wrapped in @layer components so Tailwind's later `+ "`@layer utilities`" + ` can
 * override them. Reliquary ships them unlayered, which makes every utility on a .ds-* element
 * inert (an unlayered rule beats any layered rule, whatever the specificity). @keyframes and
 * @property are hoisted out — keyframes are not subject to layers, and @property is top-level.
 *
 * Regenerate:  node scripts/layer-design-system.mjs
 */\n\n`;

const css =
  banner +
  allHoisted.join("\n\n") +
  "\n\n@layer components {\n" +
  layered.join("\n\n") +
  "\n}\n";

writeFileSync(out, css);
console.log(
  `[layer-design-system] ${files.length} recipe(s) -> ${out}\n` +
  `  hoisted out of the layer: ${allHoisted.length} (@keyframes / @property)\n` +
  `  ${(css.length / 1024).toFixed(0)} KB`
);
